def audit_business_copy(doc):
    text = "\n".join([p.text for p in doc.paragraphs] + [c.text for t in doc.tables for row in t.rows for c in row.cells])
    blocked = ["接口", "路由", "URL", "localStorage", "projectId", "tab=", ".html"]
    found = [item for item in blocked if item in text]
    if found:
        raise AssertionError(f"Technical copy remains: {found}")
    required = ["30万以内", "去掉产品类型", "服务时间、商业运营", "公园", "我的关注", "我的足迹", "AC-15"]
    missing = [item for item in required if item not in text]
    if missing:
        raise AssertionError(f"Required business copy missing: {missing}")


